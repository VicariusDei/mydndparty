-- Prerequisiti: migrazioni gruppi/ruoli e narrative_core.
CREATE TABLE IF NOT EXISTS mdp_npc_profiles (
 id INT AUTO_INCREMENT PRIMARY KEY, campaign_id INT NOT NULL, world_entity_id INT NULL,
 name VARCHAR(120) NOT NULL, personality TEXT NOT NULL, knowledge TEXT NOT NULL, memory TEXT NOT NULL,
 voice VARCHAR(30) NOT NULL DEFAULT 'alloy', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (campaign_id) REFERENCES mdp_campaigns(id) ON DELETE CASCADE,
 FOREIGN KEY (world_entity_id) REFERENCES mdp_world_entities(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mdp_npc_rooms (
 id INT AUTO_INCREMENT PRIMARY KEY, npc_id INT NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL, scene TEXT NOT NULL, approval TINYINT NOT NULL DEFAULT 1,
 paused TINYINT NOT NULL DEFAULT 0, epoch INT NOT NULL DEFAULT 0, busy_until DATETIME NULL,
 FOREIGN KEY (npc_id) REFERENCES mdp_npc_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mdp_npc_messages (
 id INT AUTO_INCREMENT PRIMARY KEY, room_id INT NOT NULL, role VARCHAR(20) NOT NULL,
 content TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'published', epoch INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (room_id) REFERENCES mdp_npc_rooms(id) ON DELETE CASCADE, INDEX room_messages (room_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mdp_npc_usage (
 id INT AUTO_INCREMENT PRIMARY KEY, room_id INT NOT NULL, operation VARCHAR(30) NOT NULL,
 usage_json TEXT NULL, success TINYINT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (room_id) REFERENCES mdp_npc_rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
